// Imports the port given as argv[2] and runs one tool call in a session chat.params never saw (family AI): tool argv[4]
// with { body: argv[3] }, or, for "bash", with { command: argv[3] }. Prints {allowed, message} as JSON.
const CHILD_PROBE = [
  "const [port, text, tool] = process.argv.slice(2)",
  "const client = { app: { log: async () => ({ data: true }) } }",
  `const hooks = await (await import(port)).${EXPORT}({ client, directory: process.cwd(), worktree: process.cwd() })`,
  "try {",
  '  const args = tool === "bash" ? { command: text } : { body: text }',
  '  await hooks["tool.execute.before"]({ tool, sessionID: "s", callID: "c" }, { args })',
  '  console.log(JSON.stringify({ allowed: true, message: "" }))',
  "} catch (error) {",
  "  console.log(JSON.stringify({ allowed: false, message: (error as Error).message }))",
  "}",
  "",
].join("\n")

describe("opencode-ai-attribution: name files, in a child bun whose HOME is the scope's", () => {
  const PASSES: ChildResult = { allowed: true, message: "" }
  const NOT_CONFIGURED: ChildResult = { allowed: false, message: SETUP_MESSAGE }

  // A child built from scratch: only PATH is inherited, so neither the real HOME nor the shell's XDG_CONFIG_HOME
  // reaches the port. OVERRIDES maps a variable to undefined to leave it unset.
  function runChild(scope: Scope, body: string, overrides: EnvVars = {}, tool = MCP_TOOL): ChildResult {
    const installed = copyPort(scope, PORT)
    const probe = join(scope.root, "probe.ts")
    writeFileSync(probe, CHILD_PROBE)
    const vars: EnvVars = {
      PATH: process.env.PATH ?? "",
      HOME: scope.home,
      XDG_CONFIG_HOME: scope.configHome,
      XDG_CACHE_HOME: join(scope.root, "cache"),
      XDG_DATA_HOME: join(scope.root, "data"),
      BUN_INSTALL_CACHE_DIR: join(scope.root, "cache", "bun"),
      TMPDIR: scope.root,
      ...overrides,
    }
    const env: Record<string, string> = {}
    for (const [key, value] of Object.entries(vars)) if (value !== undefined) env[key] = value
    const result = spawnSync(process.execPath, [probe, installed, body, tool], {
      cwd: scope.projectDir, env, encoding: "utf8", timeout: 30_000,
    })
    expect({ status: result.status, stderr: result.stderr }).toEqual({ status: 0, stderr: "" })
    return JSON.parse(result.stdout.trim()) as ChildResult
  }

  test("a primary name file that is a directory blocks with the setup message", () => {
    const scope = newScope()
    mkdirSync(primaryNameFile(scope.configHome), { recursive: true })

    expect(runChild(scope, `Fixes the timeout.\n\n${line("AI")}`)).toEqual(NOT_CONFIGURED)
  })

  test("with no name file anywhere, the post is blocked with the setup message and nothing is written", () => {
    const scope = newScope()

    const result = runChild(scope, `Fixes the timeout.\n\n${line("AI")}`)

    expect(result).toEqual(NOT_CONFIGURED)
    expect(readdirSync(scope.home, { recursive: true })).toEqual([])
    expect(existsSync(join(scope.configHome, "llm-agent-workflow"))).toBe(false)
  })

  test("a posting command with no name file anywhere is blocked with the setup message", () => {
    const scope = newScope()

    const result = runChild(scope, `gh pr comment 42 --body "Fixed the timeout. ${line("AI")}"`, {}, "bash")

    expect(result).toEqual(NOT_CONFIGURED)
  })

  test("a name only in the legacy opencode file is read, and no file is written", () => {
    const scope = newScope()
    const legacy = writeName(legacyOpencodeNameFile(scope.home), NAME)

    const result = runChild(scope, `Fixes the timeout.\n\n${line("GPT")}`)

    expect(result).toEqual(PASSES)
    expect(readFileSync(legacy, "utf8")).toBe(NAME)
    expect(existsSync(primaryNameFile(scope.configHome))).toBe(false)
    expect(existsSync(legacyClaudeCodeNameFile(scope.home))).toBe(false)
  })

  test("a name only in the legacy Claude Code file is read", () => {
    const scope = newScope()
    writeName(legacyClaudeCodeNameFile(scope.home), NAME)

    expect(runChild(scope, `Fixes the timeout.\n\n${line("GPT")}`)).toEqual(PASSES)
  })

  test("the legacy opencode file is read before the legacy Claude Code file", () => {
    const scope = newScope()
    writeName(legacyOpencodeNameFile(scope.home), NAME)
    writeName(legacyClaudeCodeNameFile(scope.home), OTHER_NAME)

    const result = runChild(scope, `Fixes the timeout.\n\n${line("AI", OTHER_NAME)}`)

    expect(result).toEqual({ allowed: false, message: missingMessage("AI", NAME) })
  })

  test("the primary file wins over both legacy files", () => {
    const scope = newScope()
    writeName(primaryNameFile(scope.configHome), NAME)
    writeName(legacyOpencodeNameFile(scope.home), OTHER_NAME)
    writeName(legacyClaudeCodeNameFile(scope.home), OTHER_NAME)

    const result = runChild(scope, `Fixes the timeout.\n\n${line("AI", OTHER_NAME)}`)

    expect(result).toEqual({ allowed: false, message: missingMessage("AI", NAME) })
  })

  test("without XDG_CONFIG_HOME, the primary file is read from HOME/.config", () => {
    const scope = newScope()
    writeName(primaryNameFile(join(scope.home, ".config")), NAME)

    const result = runChild(scope, `Fixes the timeout.\n\n${line("AI")}`, { XDG_CONFIG_HOME: undefined })

    expect(result).toEqual(PASSES)
  })

  test("a primary file under HOME/.config is not read when XDG_CONFIG_HOME points elsewhere", () => {
    const scope = newScope()
    writeName(primaryNameFile(join(scope.home, ".config")), NAME)

    expect(runChild(scope, `Fixes the timeout.\n\n${line("AI")}`)).toEqual(NOT_CONFIGURED)
  })

  test.skipIf(IS_ROOT)("an unreadable primary file (mode 000) blocks with the setup message", () => {
    const scope = newScope()
    const primary = writeName(primaryNameFile(scope.configHome), NAME)
    chmodSync(primary, 0o000)

    const result = runChild(scope, `Fixes the timeout.\n\n${line("AI")}`)
    chmodSync(primary, 0o600)

    expect(result).toEqual(NOT_CONFIGURED)
  })

  test("an undecodable primary file blocks with the setup message", () => {
    const scope = newScope()
    writeName(primaryNameFile(scope.configHome), new Uint8Array([0xff, 0xfe, 0xfa]))

    expect(runChild(scope, `Fixes the timeout.\n\n${line("AI")}`)).toEqual(NOT_CONFIGURED)
  })

  test("a primary that is a directory falls through to the legacy opencode file", () => {
    const scope = newScope()
    mkdirSync(primaryNameFile(scope.configHome), { recursive: true })
    writeName(legacyOpencodeNameFile(scope.home), NAME)

    expect(runChild(scope, `Fixes the timeout.\n\n${line("AI")}`)).toEqual(PASSES)
  })

  test("an empty primary file falls through to the legacy Claude Code file", () => {
    const scope = newScope()
    writeName(primaryNameFile(scope.configHome), "  \n")
    writeName(legacyClaudeCodeNameFile(scope.home), NAME)

    expect(runChild(scope, `Fixes the timeout.\n\n${line("AI")}`)).toEqual(PASSES)
  })
})
