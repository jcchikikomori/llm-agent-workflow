// ai-attribution opencode port Integration Test - Design Doc: docs/design/opencode-port-design.md, "Slice:
// ai-attribution". Contract: ADR-0002 (decision table, family table). ACs: AC-033, AC-034.
//
// Run with (HOME and the bun caches pointed outside the real home):
//
//   bun test plugin-attribution/tests
//
// Harness (scripts/opencode/tests/support/scope.ts):
// - Each test builds a temp scope under os.tmpdir(): HOME=<tmp>/home, XDG_CONFIG_HOME=<tmp>/config, and
//   <tmp>/config/opencode/plugins as a symlink to <tmp>/dotfiles/plugins (the live layout). The port is copied there
//   and dynamic-imported with a unique query string, so every test gets a fresh module and fresh per-session state.
// - The factory gets a fake client (client.app.log records calls). The tests drive the port's hooks directly:
//   config (MCP server names), chat.params (model family), event (session.deleted) and tool.execute.before.
// - In-process tests always write the reviewer name to the primary file under the scope's XDG_CONFIG_HOME, so the
//   port never reaches the legacy fallbacks. Those hang off os.homedir(), which Bun caches at startup: HOME set here
//   cannot move them.
// - The name-file tests that need the legacy fallbacks, or no name at all, run the port in a child bun whose HOME is
//   the scope's, so its cached os.homedir() is too. Only PATH is inherited by the child.
// - The slop, commit-trailer and validator cases are the ones plugin-attribution/tests/test_attribution_hook.py
//   asserts against the Python hook, so both runtimes keep the same pattern lists.

